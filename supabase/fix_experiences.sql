-- 학교명/학과 정정: 한양대학교 → 한양대학교 ERICA, 컴퓨터공학과 → 컴퓨터학부
update experiences
set org_name = '한양대학교 ERICA', role = '컴퓨터학부 (재학)'
where type = 'education' and org_name = '한양대학교';

-- 자람 학회 "회원"은 현재도 계속 중 — 종료일이 잘못 들어가 있었음 (진행중이면 null)
update experiences
set end_date = null
where type = 'club' and org_name = '자람 학회' and role = '회원';
